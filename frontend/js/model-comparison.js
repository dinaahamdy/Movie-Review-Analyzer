document.addEventListener('DOMContentLoaded', async () => {
  const status = document.getElementById('resultsStatus');
  const content = document.getElementById('resultsContent');
  const apiBase = 'http://127.0.0.1:5000';

  try {
    const response = await fetch(`${apiBase}/comparison-results`);
    if (!response.ok) throw new Error(`API returned ${response.status}`);
    const results = await response.json();
    if (!Array.isArray(results.models) || results.models.length === 0) {
      throw new Error('No trained model results were found yet. Run the comparison training scripts first.');
    }
    renderResults(results);
    status.hidden = true;
    content.hidden = false;
  } catch (error) {
    status.classList.add('error');
    status.textContent = `Experiment results are not available yet. ${error.message} Start the Flask backend and make sure results/comparison_results.json has been generated by the training experiments.`;
  }

  function renderResults(results) {
    const models = results.models;
    const best = [...models].sort((a,b) => (b.f1_score ?? -1) - (a.f1_score ?? -1))[0];
    const cards = [
      ['Models evaluated', models.length, 'Completed approaches'],
      ['Best F1-score', formatPct(best.f1_score), best.name],
      ['Dataset size', results.dataset?.total_reviews ?? '—', 'Reviews used in experiment'],
      ['Test samples', results.dataset?.test_samples ?? '—', 'Held-out evaluation set']
    ];
    document.getElementById('metricCards').innerHTML = cards.map(([label,value,note]) =>
      `<div class="metric-card"><small>${escapeHTML(label)}</small><strong>${escapeHTML(value)}</strong><span>${escapeHTML(note)}</span></div>`
    ).join('');

    const labels = models.map(m => m.name);
    const metricSets = [
      {label:'Accuracy',key:'accuracy',backgroundColor:'#6f5b80'},
      {label:'Precision',key:'precision',backgroundColor:'#c5a46d'},
      {label:'Recall',key:'recall',backgroundColor:'#9aaf9b'},
      {label:'F1-score',key:'f1_score',backgroundColor:'#d9aeb5'}
    ];
    new Chart(document.getElementById('metricsChart'), {
      type:'bar',
      data:{labels,datasets:metricSets.map(s=>({label:s.label,data:models.map(m=>toPercent(m[s.key])),backgroundColor:s.backgroundColor,borderRadius:5}))},
      options:{responsive:true,scales:{y:{beginAtZero:true,max:100,ticks:{callback:v=>v+'%'}}},plugins:{legend:{position:'bottom'}}}
    });

    new Chart(document.getElementById('timeChart'), {
      type:'bar',
      data:{labels,datasets:[{label:'Training time (seconds)',data:models.map(m=>m.training_seconds ?? null),backgroundColor:'#b89a70',borderRadius:5}]},
      options:{responsive:true,scales:{y:{beginAtZero:true}},plugins:{legend:{display:false}}}
    });

    const rocDatasets = models.filter(m=>Array.isArray(m.roc_curve?.fpr) && Array.isArray(m.roc_curve?.tpr))
      .map((m,i)=>({label:m.name,data:m.roc_curve.fpr.map((x,j)=>({x,y:m.roc_curve.tpr[j]})),borderWidth:2,pointRadius:0,tension:.1}));
    if (rocDatasets.length) {
      new Chart(document.getElementById('rocChart'), {
        type:'line',data:{datasets:rocDatasets},
        options:{responsive:true,parsing:false,scales:{x:{type:'linear',min:0,max:1,title:{display:true,text:'False Positive Rate'}},y:{min:0,max:1,title:{display:true,text:'True Positive Rate'}}},plugins:{legend:{position:'bottom'}}}
      });
    } else {
      document.getElementById('rocChart').insertAdjacentHTML('afterend','<p class="method-note">ROC curve data was not included in the experiment output.</p>');
    }

    const confusion = document.getElementById('confusionMatrices');
    confusion.innerHTML = models.filter(m=>Array.isArray(m.confusion_matrix)).map(m=>{
      const cm=m.confusion_matrix;
      return `<article class="research-card confusion-card"><h4>${escapeHTML(m.name)}</h4>
      <table><thead><tr><th></th><th>Predicted Negative</th><th>Predicted Positive</th></tr></thead>
      <tbody><tr><th>Actual Negative</th><td>${Number(cm[0]?.[0] ?? 0)}</td><td>${Number(cm[0]?.[1] ?? 0)}</td></tr>
      <tr><th>Actual Positive</th><td>${Number(cm[1]?.[0] ?? 0)}</td><td>${Number(cm[1]?.[1] ?? 0)}</td></tr></tbody></table></article>`;
    }).join('') || '<p class="method-note">Confusion matrix data was not included in the experiment output.</p>';

    const split = results.dataset?.split;
    document.getElementById('experimentDetails').textContent =
      `Experiment details: ${results.dataset?.total_reviews ?? 'Unknown'} reviews; `+
      `${results.dataset?.train_samples ?? 'Unknown'} training samples; `+
      `${results.dataset?.test_samples ?? 'Unknown'} test samples. `+
      `Split: ${split ?? 'not specified'}. `+
      `Best F1-score: ${best.name} (${formatPct(best.f1_score)}). `+
      `Generated at: ${results.generated_at ?? 'not specified'}.`;
    document.getElementById('conclusionText').textContent =
      `In this run, ${best.name} achieved the highest F1-score (${formatPct(best.f1_score)}). `+
      `This result should be interpreted together with its precision, recall, accuracy, confusion matrix and training time.`;
  }

  function toPercent(value) {
    if (value === null || value === undefined || Number.isNaN(Number(value))) return null;
    const n=Number(value);
    return n <= 1 ? +(n*100).toFixed(2) : +n.toFixed(2);
  }
  function formatPct(value) { const n=toPercent(value); return n===null ? '—' : `${n.toFixed(2)}%`; }
  function escapeHTML(value) { return String(value ?? '').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); }
});
